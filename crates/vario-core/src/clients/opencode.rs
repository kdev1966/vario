//! OpenCode: sub-agents in `<config>/agents/*.md` (`mode: subagent`, named after the
//! file), the delegation guidance in the global rules file, and a plugin in
//! `<config>/plugins/vario.js` that journals each delegation, for every project.
//! `<config>` is `$XDG_CONFIG_HOME/opencode`, or `~/.config/opencode`, on every system.

use std::path::PathBuf;

use super::subagents::{self, MARKER, Subagent, Tier, yaml_string};
use super::{Env, Integration, has_mcp_server};
use crate::files;
use crate::handoff;
use crate::parts::{Kind, MarkdownBlock, OwnFile, Part};

pub fn integration() -> Integration {
    Integration {
        name: "opencode",
        label: "OpenCode",
        detect: |env| env.which("opencode").is_some() || config_dir(env).is_dir(),
        parts,
        handoff_connected: |env| {
            config_files(env)
                .iter()
                .any(|path| has_mcp_server(path, "mcp", handoff::SERVER_NAME))
        },
    }
}

fn config_dir(env: &Env) -> PathBuf {
    env.var("XDG_CONFIG_HOME")
        .map(PathBuf::from)
        .unwrap_or_else(|| env.home.join(".config"))
        .join("opencode")
}

/// The global configuration: `$OPENCODE_CONFIG` if set, then `opencode.json` and
/// `opencode.jsonc` in the configuration directory.
fn config_files(env: &Env) -> Vec<PathBuf> {
    let dir = config_dir(env);
    env.var("OPENCODE_CONFIG")
        .map(PathBuf::from)
        .into_iter()
        .chain([dir.join("opencode.json"), dir.join("opencode.jsonc")])
        .collect()
}

/// OpenCode reads the first of `<config>/AGENTS.md` and `~/.claude/CLAUDE.md`, unless
/// its Claude Code fallback is disabled. Creating `AGENTS.md` would silently stop it
/// from reading the user's `CLAUDE.md`, so the guidance goes into the file OpenCode
/// reads now.
fn rules_file(env: &Env) -> PathBuf {
    let agents = config_dir(env).join("AGENTS.md");
    let claude = env.home.join(".claude").join("CLAUDE.md");
    let fallback_disabled = env.var("OPENCODE_DISABLE_CLAUDE_CODE").is_some()
        || env.var("OPENCODE_DISABLE_CLAUDE_CODE_PROMPT").is_some();
    if agents.exists() || fallback_disabled || !claude.is_file() {
        agents
    } else {
        claude
    }
}

/// Models are `provider/model` and depend on the providers the user set up. The
/// economical tier uses the user's `small_model`, which OpenCode keeps for light
/// tasks; without one, and for the intermediate tier, the sub-agent inherits the
/// model of the agent that calls it. A configuration with comments (JSONC) is not
/// read, so its `small_model` is not used.
fn model(tier: Tier, env: &Env) -> Option<String> {
    match tier {
        Tier::Economical => config_files(env).iter().find_map(|path| {
            files::read_json(path)
                .ok()?
                .get("small_model")?
                .as_str()
                .filter(|model| !model.is_empty())
                .map(str::to_owned)
        }),
        Tier::Intermediate => None,
    }
}

fn parts(env: &Env) -> Vec<Box<dyn Part>> {
    let dir = config_dir(env).join("agents");
    let mut parts: Vec<Box<dyn Part>> = subagents::all()
        .iter()
        .map(|subagent| -> Box<dyn Part> {
            Box::new(OwnFile {
                path: dir.join(format!("{}.md", subagent.name)),
                content: render(subagent, model(subagent.tier, env).as_deref()),
                kind: Kind::Subagents,
                marker: Some(MARKER.into()),
            })
        })
        .collect();
    parts.push(Box::new(MarkdownBlock {
        path: rules_file(env),
        body: subagents::INSTRUCTIONS.into(),
    }));
    parts.push(Box::new(OwnFile {
        path: config_dir(env).join("plugins").join("vario.js"),
        content: plugin(env),
        kind: Kind::Hooks,
        marker: Some(PLUGIN_MARKER.into()),
    }));
    parts
}

const PLUGIN_MARKER: &str = "// Generated by Vario";

/// OpenCode has no hook commands, only plugins. This one runs
/// `vario hook session-start --via opencode` when OpenCode starts, which opens the
/// floating gauge, reports the main session's model and usage (from the events, since
/// the terminal interface gives the plugin no reachable API) so the gauge follows the
/// client in use, then waits for a sub-agent's session (a child session) to go idle and
/// passes its final answer to `vario hook subagent-stop --via opencode`, in Cursor's
/// shape.
fn plugin(env: &Env) -> String {
    let exe = env.exe.to_string_lossy();
    let exe = if exe.is_empty() { "vario".into() } else { exe };
    let names: Vec<&str> = subagents::all()
        .iter()
        .map(|subagent| subagent.name)
        .collect();
    let template = r#"// Generated by Vario; removed by 'vario remove'.
// Opens Vario's floating gauge when OpenCode starts, reports the main session's model
// and usage so the gauge shows the client in use, and journals each delegation to
// Vario's sub-agents: when a sub-agent's session goes idle, its final answer goes to
// `vario hook subagent-stop --via opencode`.
const VARIO = __EXE__;
const AGENTS = __AGENTS__;
const recorded = new Set();

export const VarioPlugin = async ({ client, $ }) => {
  try {
    await $`${VARIO} hook session-start --via opencode < ${new Response("{}")}`
      .quiet()
      .nothrow();
  } catch {
    // A hook never gets in the way.
  }

  // Report a session's model and usage, so the gauge follows the client in use. The
  // terminal interface gives the plugin no reachable API, so this reads the event's
  // payload, never `client.session`.
  const report = async (info) => {
    const id = info.sessionID ?? info.id;
    if (!id) return;
    const tokens = info.tokens ?? {};
    const input = JSON.stringify({
      model: info.modelID ?? info.model?.id ?? info.model?.modelID ?? null,
      agent: info.agent ?? info.mode ?? null,
      cost: typeof info.cost === "number" ? info.cost : 0,
      input: tokens.input ?? 0,
      output: tokens.output ?? 0,
      reasoning: tokens.reasoning ?? 0,
      cache_read: tokens.cache?.read ?? 0,
      cache_write: tokens.cache?.write ?? 0,
      directory: info.path?.cwd ?? info.directory ?? null,
      session: id,
    });
    await $`${VARIO} hook activity --via opencode < ${new Response(input)}`
      .quiet()
      .nothrow();
  };

  // The sessions that are not a sub-agent's, and their latest report.
  const main = new Set();
  const newest = new Map();

  return {
    event: async ({ event }) => {
      const props = event.properties ?? {};
      // A session's whole state: model, agent, tokens, cost. A session with a parent is
      // a sub-agent's, which the gauge does not follow.
      if (event.type === "session.updated") {
        const info = props.info;
        if (info && !info.parentID) {
          const first = !main.has(info.id);
          main.add(info.id);
          if (first) await report(info);
        }
        return;
      }
      // The assistant's reply; its updates carry the running token and cost totals.
      if (event.type === "message.updated") {
        const info = props.info;
        // Switch as soon as a prompt is submitted, before the assistant replies.
        if (info?.role === "user" && main.has(info.sessionID)) {
          await report(info);
          return;
        }
        if (info?.role === "assistant" && main.has(info.sessionID)) {
          newest.set(info.sessionID, info);
        }
        return;
      }
      // A turn just ended: report the state as it stands.
      if (event.type === "session.status" && props.status?.type === "idle") {
        const info = newest.get(props.sessionID);
        if (info) await report(info);
        return;
      }
      // A sub-agent's session went idle: journal its final answer.
      if (event.type !== "session.idle") return;
      const id = props.sessionID;
      if (!id) return;
      if (main.has(id)) {
        const info = newest.get(id);
        if (info) await report(info);
        return;
      }
      try {
        const session = (await client.session.get({ path: { id } })).data;
        if (!session?.parentID || recorded.has(id)) return;
        const messages = (await client.session.messages({ path: { id } })).data ?? [];
        const agent = messages.find((m) => m.info.role === "user")?.info.agent;
        if (!AGENTS.includes(agent)) return;
        recorded.add(id);
        const last = messages.findLast((m) => m.info.role === "assistant");
        const summary = (last?.parts ?? [])
          .filter((part) => part.type === "text")
          .map((part) => part.text)
          .join("\n");
        const input = JSON.stringify({
          subagent_type: agent,
          summary,
          cwd: session.directory,
          subagent_model: last ? `${last.info.providerID}/${last.info.modelID}` : null,
          cost: last?.info.cost ?? null,
          tokens: last?.info.tokens ?? null,
        });
        await $`${VARIO} hook subagent-stop --via opencode < ${new Response(input)}`
          .quiet()
          .nothrow();
      } catch {
        // A hook never gets in the way.
      }
    },
  };
};
"#;
    template
        .replace(
            "__EXE__",
            &serde_json::to_string(&exe).expect("a string serializes"),
        )
        .replace(
            "__AGENTS__",
            &serde_json::to_string(&names).expect("a list serializes"),
        )
}

fn render(subagent: &Subagent, model: Option<&str>) -> String {
    let mut header = format!(
        "description: {}\nmode: subagent\n",
        yaml_string(subagent.description)
    );
    if let Some(model) = model {
        header += &format!("model: {}\n", yaml_string(model));
    }
    if subagent.read_only {
        header += "permission:\n  edit: deny\n  bash: deny\n";
    }
    format!("---\n{header}---\n\n{}", subagents::body(subagent))
}
