//! The sub-agents and the delegation guidance Vario installs, independent of any client.
//! Each client adapter renders them in its own file format.

/// Capability level of a model. Each client maps it to one of its own models.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Tier {
    Economical,
    Intermediate,
}

pub struct Subagent {
    pub name: &'static str,
    /// When the client should delegate to it; clients choose sub-agents from this text.
    pub description: &'static str,
    pub tier: Tier,
    /// Read-only sub-agents get no editing or shell tools.
    pub read_only: bool,
    pub prompt: &'static str,
}

/// Identifies the files Vario generated; a file without it is never touched.
pub const MARKER: &str = "<!-- Generated by Vario";
pub const MARKER_LINE: &str = "<!-- Generated by Vario; removed by 'vario remove'. -->";

const REPORT_FOOTER: &str = "\
End every answer with this footer:

```
RESULT: <one line>
CHECKS: <commands run and their results, or \"none\">
UNCERTAINTIES: <or \"none\">
ESCALATE: yes|no - <reason>
```";

pub fn all() -> Vec<Subagent> {
    vec![
        Subagent {
            name: "vario-reader",
            description: "Use proactively to read and summarize without changing anything: locate code, extract fields or values, summarize a file, a document or the large output of a tool. Returns only a short summary.",
            tier: Tier::Economical,
            read_only: true,
            prompt: "\
You read and summarize. You change nothing and make no design decision.

- Read the pointers you receive (files and lines, identifiers) yourself; never ask for the content to be pasted.
- Return only what the GOAL asks for, as briefly as possible: paths with line numbers, extracted values, a summary in a few lines.
- If the brief is ambiguous or the information cannot be found, say so instead of guessing.",
        },
        Subagent {
            name: "vario-worker",
            description: "Use proactively to carry out a task that is already defined and bounded, when the brief gives a check: rename, apply a known pattern, make a precise change, run a known sequence of commands. No design, no decisions.",
            tier: Tier::Intermediate,
            read_only: false,
            prompt: "\
You carry out a task defined by the main session. You change neither its goal nor its scope.

- Read the pointers you receive yourself; touch only the files the task needs.
- Respect the CONSTRAINTS. No destructive operation (deleting, `git reset`, `push`, overwriting) unless the brief says so.
- Run the requested CHECK and report its exact result. If it fails, one obvious fix is allowed; otherwise stop and report.
- If the task needs a design choice or the brief is ambiguous, stop and ask for escalation instead of guessing.",
        },
    ]
}

/// A double-quoted YAML scalar, safe whatever the text holds (`: `, `#`, quotes).
pub(super) fn yaml_string(text: &str) -> String {
    format!("\"{}\"", text.replace('\\', "\\\\").replace('"', "\\\""))
}

/// The full system prompt of a sub-agent, after its client-specific header.
pub fn body(subagent: &Subagent) -> String {
    format!("{MARKER_LINE}\n\n{}\n\n{REPORT_FOOTER}\n", subagent.prompt)
}

/// Guidance for the main session, placed in the client's global instructions file.
pub const INSTRUCTIONS: &str = "\
## Vario: delegate to economical sub-agents

Keep design, debugging, trade-offs and review in this session; delegate the rest.
- Reading and summarizing → `vario-reader`.
- A well-defined task with a check → `vario-worker`.
- Always keep here: security-sensitive or destructive changes, ambiguous requests, anything that needs the user's judgment.

Brief with pointers, never pasted content:

```
GOAL: <expected result, one sentence>
INPUTS: <files and lines, identifiers, parameters>
CONSTRAINTS: <what not to do, expected format>
CHECK: <command or criterion that proves success>
```

\"ESCALATE: yes\" is only a hint. A failed check → retry once one level up (`vario-reader` → `vario-worker`, read-only; `vario-worker` → do it here). With no possible check, review the result; if it falls short, do it here.";
