//! OpenAI Codex CLI: sub-agents in `<home>/agents/*.toml`, the delegation guidance
//! in `<home>/AGENTS.md`, and a `SubagentStop` hook in `<home>/hooks.json`, for every
//! project. `<home>` is `$CODEX_HOME`, or `~/.codex`.
//!
//! Codex delegates only when asked to, or when its instructions say so: the guidance
//! block is what makes it use Vario's sub-agents. Hooks Codex does not manage must be
//! approved once with `/hooks` before they run.

use std::path::PathBuf;

use serde_json::{Map, json};

use super::subagents::{self, Subagent, Tier};
use super::{Env, Integration};
use crate::files;
use crate::handoff;
use crate::parts::{JsonHooks, Kind, MarkdownBlock, OwnFile, Part};

/// Identifies Vario's agent files (TOML comments).
const MARKER: &str = "# Generated by Vario";

pub fn integration() -> Integration {
    Integration {
        name: "codex",
        label: "Codex",
        detect: |env| env.which("codex").is_some() || config_dir(env).is_dir(),
        parts,
        handoff_connected: |env| {
            // `[mcp_servers.handoff]` in config.toml; a plain text search keeps Vario
            // free of a TOML parser.
            files::read_text(&config_dir(env).join("config.toml")).is_ok_and(|text| {
                text.lines().any(|line| {
                    let line = line.trim();
                    line == format!("[mcp_servers.{}]", handoff::SERVER_NAME)
                        || line == format!("[mcp_servers.\"{}\"]", handoff::SERVER_NAME)
                })
            })
        },
    }
}

fn config_dir(env: &Env) -> PathBuf {
    env.var("CODEX_HOME")
        .map(PathBuf::from)
        .unwrap_or_else(|| env.home.join(".codex"))
}

/// `AGENTS.override.md` replaces `AGENTS.md` when it exists.
fn rules_file(env: &Env) -> PathBuf {
    let dir = config_dir(env);
    let override_file = dir.join("AGENTS.override.md");
    if override_file.is_file() {
        override_file
    } else {
        dir.join("AGENTS.md")
    }
}

/// The economical tier names Codex's most efficient model; the intermediate tier
/// inherits the parent's, so a bounded task is never done by a weaker model than
/// the session chose.
fn model(tier: Tier) -> Option<&'static str> {
    match tier {
        Tier::Economical => Some("gpt-6-luna"),
        Tier::Intermediate => None,
    }
}

fn parts(env: &Env) -> Vec<Box<dyn Part>> {
    let dir = config_dir(env);
    let mut parts: Vec<Box<dyn Part>> = subagents::all()
        .iter()
        .map(|subagent| -> Box<dyn Part> {
            Box::new(OwnFile {
                path: dir.join("agents").join(format!("{}.toml", subagent.name)),
                content: render(subagent),
                kind: Kind::Subagents,
                marker: Some(MARKER.into()),
            })
        })
        .collect();
    parts.push(Box::new(MarkdownBlock {
        path: rules_file(env),
        body: subagents::INSTRUCTIONS.into(),
    }));
    parts.push(Box::new(JsonHooks {
        path: dir.join("hooks.json"),
        keys: vec!["hooks".into()],
        entries: vec![
            (
                "SessionStart".into(),
                json!({
                    "matcher": "startup|resume",
                    "hooks": [{
                        "type": "command",
                        "command": env.hook_command("session-start", "codex"),
                        "timeout": 5,
                    }],
                }),
            ),
            (
                "SubagentStop".into(),
                json!({
                    "hooks": [{
                        "type": "command",
                        "command": env.hook_command("subagent-stop", "codex"),
                        "timeout": 10,
                    }],
                }),
            ),
        ],
        defaults: Map::new(),
        kind: Kind::Hooks,
    }));
    parts
}

/// A TOML string, safe whatever the text holds.
fn toml_string(text: &str) -> String {
    format!("\"{}\"", text.replace('\\', "\\\\").replace('"', "\\\""))
}

fn render(subagent: &Subagent) -> String {
    let mut toml = format!(
        "{MARKER}; removed by 'vario remove'.\nname = {}\ndescription = {}\n",
        toml_string(subagent.name),
        toml_string(subagent.description),
    );
    if let Some(model) = model(subagent.tier) {
        toml += &format!("model = {}\n", toml_string(model));
    }
    // A literal string: the prompt is kept exactly, backslashes and quotes included.
    toml += &format!(
        "developer_instructions = '''\n{}'''\n",
        subagents::body(subagent)
    );
    if subagent.read_only {
        // Codex has no read-only sub-agent; without a shell, it can only read.
        toml += "\n[features]\nshell_tool = false\n";
    }
    toml
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_prompt_fits_a_literal_string() {
        for subagent in subagents::all() {
            assert!(!subagents::body(&subagent).contains("'''"));
        }
    }

    #[test]
    fn the_reader_has_no_shell_and_a_cheap_model() {
        let all = subagents::all();
        let reader = render(&all[0]);
        assert!(reader.starts_with("# Generated by Vario"));
        assert!(reader.contains("\nname = \"vario-reader\"\n"));
        assert!(reader.contains("\nmodel = \"gpt-6-luna\"\n"));
        assert!(reader.ends_with("\n[features]\nshell_tool = false\n"));
        let worker = render(&all[1]);
        assert!(!worker.contains("model ="), "the worker inherits the model");
        assert!(!worker.contains("[features]"));
    }
}
