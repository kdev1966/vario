//! Kiro CLI (successor to Amazon Q Developer CLI): one agent JSON file per role in
//! `<global>/agents/`, the delegation guidance in the agent's `prompt` field, and
//! hooks (`agentSpawn`, `userPromptSubmit`) in the same file. `<global>` is
//! `~/.kiro/agents` (Kiro CLI) or `~/.aws/amazonq/cli-agents` (Amazon Q CLI); both are checked.
//!
//! Kiro has no sub-agent mechanism in its released format: the reader and worker are
//! installed as separate agents the user selects with `--agent`. The delegation
//! guidance in each agent's `prompt` tells the main session when to delegate.
//! Hooks carry only `cwd`; no model, session ID or tokens are in the payload, so the
//! gauge shows the client name alone (mode `other`, no `usage`).

use std::path::{Path, PathBuf};
use std::process::Command;
use std::sync::Mutex;
use std::time::{Duration, Instant};

use serde_json::{Map, Value, json};

use super::subagents::{self, Subagent, Tier};
use super::{Env, Integration, has_mcp_server};
use crate::error::Result;
use crate::files::Session;
use crate::handoff;
use crate::parts::{Kind, OwnFile, Part};

/// Field Vario sets to mark the main agent as the suggested default.
const DEFAULT_KEY: &str = "_default";

/// Identifies the files Vario generated (JSON comment field).
const MARKER: &str = "Generated by Vario";
/// The field name Vario uses to mark its files.
const MARKER_KEY: &str = "_vario";

pub fn integration() -> Integration {
    Integration {
        name: "kiro",
        label: "Kiro CLI",
        detect: |env| {
            env.which("kiro-cli").is_some()
                || env.which("q").is_some()
                || kiro_dir(env).is_dir()
                || env.home.join(".kiro").is_dir()
                || amazonq_dir(env).is_dir()
                || env.home.join(".aws").join("amazonq").is_dir()
        },
        parts,
        handoff_connected: |env| {
            has_mcp_server(
                &env.home.join(".kiro").join("settings").join("mcp.json"),
                "mcpServers",
                handoff::SERVER_NAME,
            )
        },
    }
}

/// Kiro CLI's global agent directory (the one `kiro-cli agent list` reads).
fn kiro_dir(env: &Env) -> PathBuf {
    env.home.join(".kiro").join("agents")
}

/// Amazon Q CLI's global agent directory (legacy path, still present on some machines).
fn amazonq_dir(env: &Env) -> PathBuf {
    env.home.join(".aws").join("amazonq").join("cli-agents")
}

/// All agent directories that exist on this machine, in preference order.
fn agent_dirs(env: &Env) -> Vec<PathBuf> {
    [kiro_dir(env), amazonq_dir(env)]
        .into_iter()
        .filter(|dir| dir.is_dir())
        .collect()
}

/// The first existing agent directory, or Kiro's path as the default install target.
fn primary_dir(env: &Env) -> PathBuf {
    agent_dirs(env)
        .into_iter()
        .next()
        .unwrap_or_else(|| kiro_dir(env))
}

/// `claude-haiku-4.5` is the cheapest named model in Kiro's model picker (0.40×);
/// the worker inherits the session's model so a bounded task is never done by a
/// weaker model than the session chose.
fn model(tier: Tier) -> Option<&'static str> {
    match tier {
        Tier::Economical => Some("claude-haiku-4.5"),
        Tier::Intermediate => None,
    }
}

fn parts(env: &Env) -> Vec<Box<dyn Part>> {
    let dir = primary_dir(env);
    let mut parts: Vec<Box<dyn Part>> = subagents::all()
        .iter()
        .map(|subagent| -> Box<dyn Part> {
            Box::new(OwnFile {
                path: dir.join(format!("{}.json", subagent.name)),
                content: render(subagent, env),
                kind: Kind::Subagents,
                marker: Some(MARKER.into()),
            })
        })
        .collect();
    // The main agent: all tools, hooks, and a _default marker so the user can
    // set it as default with `kiro-cli agent set-default vario`.
    parts.push(Box::new(OwnFile {
        path: dir.join("vario.json"),
        content: render_main(env),
        kind: Kind::Subagents,
        marker: Some(MARKER.into()),
    }));
    // A read-only Part that makes `doctor` show the Hooks column: the hooks live
    // inside the agent JSON files (written by OwnFile above), so apply and remove
    // are no-ops here.
    parts.push(Box::new(KiroHooks { dir: dir.clone() }));
    // A read-only Part that surfaces whether `vario` is the active default agent.
    parts.push(Box::new(KiroSetDefault {
        dir,
        kiro: kiro_program(env),
    }));
    parts
}

/// Reports whether Vario's hooks are present in the agent JSON files.
/// Writing and removing are handled by the `OwnFile` parts above.
struct KiroHooks {
    dir: PathBuf,
}

impl Part for KiroHooks {
    fn kind(&self) -> Kind {
        Kind::Hooks
    }

    fn apply(&self, _session: &mut Session) -> Result<()> {
        Ok(())
    }

    fn remove(&self, _session: &mut Session) -> Result<()> {
        Ok(())
    }

    /// The hooks are present when at least one agent JSON contains both Vario hook
    /// commands (sub-agents or the main vario agent).
    fn present(&self) -> bool {
        let candidates = subagents::all()
            .iter()
            .map(|s| format!("{}.json", s.name))
            .chain(std::iter::once("vario.json".to_string()))
            .collect::<Vec<_>>();
        candidates.iter().any(|name| {
            let path = self.dir.join(name);
            let Ok(text) = std::fs::read_to_string(&path) else {
                return false;
            };
            text.contains("session-start --via kiro") && text.contains("activity --via kiro")
        })
    }
}

/// Surfaces whether `vario` is the active default agent in Kiro CLI.
/// `apply` and `remove` are no-ops: the user sets the default with
/// `kiro-cli agent set-default vario` (shown in the install summary).
struct KiroSetDefault {
    dir: PathBuf,
    /// The `kiro-cli` (or `q`) that can confirm the default, if one is installed.
    kiro: Option<PathBuf>,
}

impl Part for KiroSetDefault {
    fn kind(&self) -> Kind {
        Kind::Instructions
    }

    fn apply(&self, _session: &mut Session) -> Result<()> {
        Ok(())
    }

    fn remove(&self, _session: &mut Session) -> Result<()> {
        Ok(())
    }

    /// `vario` is the default when `vario.json` exists and carries `_default: true`,
    /// and `kiro-cli agent list` (if available) shows `vario` with a `*`.
    fn present(&self) -> bool {
        let path = self.dir.join("vario.json");
        let Ok(text) = std::fs::read_to_string(&path) else {
            return false;
        };
        let Ok(value) = serde_json::from_str::<Value>(&text) else {
            return false;
        };
        if value.get(DEFAULT_KEY).and_then(Value::as_bool) != Some(true) {
            return false;
        }
        // If kiro-cli is available, confirm it reports vario as the default.
        let Some(kiro) = &self.kiro else {
            // kiro-cli not found on PATH: trust the JSON marker alone.
            return true;
        };
        agent_list(kiro)
            .is_some_and(|out| out.lines().any(|l| l.contains('*') && l.contains("vario")))
    }
}

/// `kiro-cli agent list` takes over a second, and one look at the clients reads it three
/// times (detection, install check, status): its output is kept this long.
const AGENT_LIST_FOR: Duration = Duration::from_secs(2);

/// The last `agent list` output, with the program that gave it and when.
type AgentList = Option<(PathBuf, Instant, Option<String>)>;
static AGENT_LIST: Mutex<AgentList> = Mutex::new(None);

/// What `kiro agent list` prints, read again only once the last reading is stale.
fn agent_list(kiro: &Path) -> Option<String> {
    // Held while the command runs: a concurrent look waits, then reuses the output.
    let mut cached = AGENT_LIST
        .lock()
        .unwrap_or_else(|poisoned| poisoned.into_inner());
    if let Some((program, at, out)) = cached.as_ref()
        && program == kiro
        && at.elapsed() < AGENT_LIST_FOR
    {
        return out.clone();
    }
    let out = Command::new(kiro)
        .args(["agent", "list"])
        .output()
        .ok()
        .and_then(|out| {
            // kiro-cli writes to stderr when stdout is not a TTY.
            let stdout = String::from_utf8(out.stdout).unwrap_or_default();
            let stderr = String::from_utf8(out.stderr).unwrap_or_default();
            let text = if stdout.is_empty() { stderr } else { stdout };
            if text.is_empty() { None } else { Some(text) }
        });
    *cached = Some((kiro.to_path_buf(), Instant::now(), out.clone()));
    out
}

/// The `kiro-cli` next to `vario`, else `kiro-cli` or `q` on the `PATH` that `env` gives.
fn kiro_program(env: &Env) -> Option<PathBuf> {
    env.exe
        .parent()
        .map(|dir| dir.join("kiro-cli"))
        .filter(|path| path.is_file())
        .or_else(|| env.which("kiro-cli"))
        .or_else(|| env.which("q"))
}

/// The commands run when a Vario agent starts: Vario's own, then Delest's disk check
/// when Delest is installed. Kiro runs only the hooks of the selected agent, so
/// Vario's agents carry Delest's too (`delest hook session-start --via kiro`).
fn spawn_hooks(env: &Env) -> Value {
    let mut hooks = vec![json!({ "command": env.hook_command("session-start", "kiro") })];
    if let Some(delest) = env.which("delest") {
        let program = delest.to_string_lossy();
        let program = if program.contains([' ', '"', '\'']) {
            format!("\"{program}\"")
        } else {
            program.into_owned()
        };
        hooks.push(json!({ "command": format!("{program} hook session-start --via kiro") }));
    }
    Value::Array(hooks)
}

/// Renders the main `vario.json` agent: all tools, hooks, delegation guidance,
/// and `_default: true` so `doctor` can detect whether it is the active default.
fn render_main(env: &Env) -> String {
    let mut agent: Map<String, Value> = Map::new();
    agent.insert(MARKER_KEY.into(), Value::from(MARKER));
    agent.insert(DEFAULT_KEY.into(), Value::from(true));
    agent.insert("name".into(), Value::from("vario"));
    agent.insert(
        "description".into(),
        Value::from(
            "Main Vario session. Delegates reading to vario-reader and bounded tasks to \
             vario-worker. Set as default with: kiro-cli agent set-default vario",
        ),
    );
    agent.insert("prompt".into(), Value::from(subagents::INSTRUCTIONS));
    agent.insert(
        "allowedTools".into(),
        json!(["fs_read", "fs_write", "execute_bash"]),
    );
    agent.insert(
        "hooks".into(),
        json!({
            "agentSpawn": spawn_hooks(env),
            "userPromptSubmit": [{ "command": env.hook_command("activity", "kiro") }],
        }),
    );
    agent.insert("mcpServers".into(), json!({}));
    serde_json::to_string_pretty(&Value::Object(agent)).expect("agent JSON serializes") + "\n"
}

fn render(subagent: &Subagent, env: &Env) -> String {
    let tools: Value = if subagent.read_only {
        json!(["fs_read", "fs_write"])
    } else {
        json!(["fs_read", "fs_write", "execute_bash"])
    };
    let mut agent: Map<String, Value> = Map::new();
    agent.insert(MARKER_KEY.into(), Value::from(MARKER));
    agent.insert("name".into(), Value::from(subagent.name));
    agent.insert("description".into(), Value::from(subagent.description));
    agent.insert(
        "prompt".into(),
        Value::from(format!(
            "{}\n\n{}",
            subagents::INSTRUCTIONS,
            subagents::body(subagent)
        )),
    );
    if let Some(model) = model(subagent.tier) {
        agent.insert("model".into(), Value::from(model));
    }
    agent.insert("allowedTools".into(), tools);
    agent.insert(
        "hooks".into(),
        json!({
            "agentSpawn": spawn_hooks(env),
            "userPromptSubmit": [{ "command": env.hook_command("activity", "kiro") }],
        }),
    );
    agent.insert("mcpServers".into(), json!({}));
    serde_json::to_string_pretty(&Value::Object(agent)).expect("agent JSON serializes") + "\n"
}

#[cfg(test)]
mod tests {
    use super::*;

    fn env_with_kiro(dir: &std::path::Path) -> Env {
        std::fs::create_dir_all(dir.join(".kiro").join("agents")).unwrap();
        Env {
            home: dir.to_path_buf(),
            ..Env::default()
        }
    }

    #[test]
    fn detects_when_kiro_dir_exists() {
        let dir = tempfile::tempdir().unwrap();
        let env = env_with_kiro(dir.path());
        assert!((integration().detect)(&env));
    }

    #[test]
    fn detects_when_amazonq_dir_exists() {
        let dir = tempfile::tempdir().unwrap();
        std::fs::create_dir_all(dir.path().join(".aws").join("amazonq").join("cli-agents"))
            .unwrap();
        let env = Env {
            home: dir.path().to_path_buf(),
            ..Env::default()
        };
        assert!((integration().detect)(&env));
    }

    #[test]
    fn reader_has_economical_model_and_read_only_tools() {
        let dir = tempfile::tempdir().unwrap();
        let env = env_with_kiro(dir.path());
        let all = subagents::all();
        let reader = render(&all[0], &env);
        let value: Value = serde_json::from_str(&reader).unwrap();
        assert_eq!(value["model"], "claude-haiku-4.5");
        assert_eq!(value["name"], "vario-reader");
        assert_eq!(value[MARKER_KEY], MARKER);
        let tools = value["allowedTools"].as_array().unwrap();
        assert!(!tools.iter().any(|t| t == "execute_bash"));
    }

    #[test]
    fn worker_inherits_model_and_has_shell() {
        let dir = tempfile::tempdir().unwrap();
        let env = env_with_kiro(dir.path());
        let all = subagents::all();
        let worker = render(&all[1], &env);
        let value: Value = serde_json::from_str(&worker).unwrap();
        assert!(
            value.get("model").is_none_or(Value::is_null),
            "worker inherits"
        );
        let tools = value["allowedTools"].as_array().unwrap();
        assert!(tools.iter().any(|t| t == "execute_bash"));
    }

    #[test]
    fn hooks_use_the_right_events() {
        let dir = tempfile::tempdir().unwrap();
        let env = env_with_kiro(dir.path());
        let all = subagents::all();
        let agent: Value = serde_json::from_str(&render(&all[0], &env)).unwrap();
        let hooks = &agent["hooks"];
        assert!(hooks.get("agentSpawn").is_some());
        assert!(hooks.get("userPromptSubmit").is_some());
        let spawn_cmd = hooks["agentSpawn"][0]["command"].as_str().unwrap();
        assert!(spawn_cmd.contains("session-start"));
        assert!(spawn_cmd.contains("--via kiro"));
    }

    #[test]
    fn delest_s_check_joins_the_spawn_hooks_when_delest_is_installed() {
        let dir = tempfile::tempdir().unwrap();
        let mut env = env_with_kiro(dir.path());
        let all = subagents::all();
        let spawn = |env: &Env| {
            let agent: Value = serde_json::from_str(&render(&all[0], env)).unwrap();
            agent["hooks"]["agentSpawn"].as_array().unwrap().clone()
        };
        assert_eq!(spawn(&env).len(), 1, "no Delest, no entry");
        let bin = dir.path().join("bin");
        std::fs::create_dir_all(&bin).unwrap();
        std::fs::write(bin.join("delest"), "").unwrap();
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            std::fs::set_permissions(bin.join("delest"), std::fs::Permissions::from_mode(0o755))
                .unwrap();
        }
        env.vars.insert("PATH".into(), bin.clone().into_os_string());
        let hooks = spawn(&env);
        assert_eq!(hooks.len(), 2);
        assert_eq!(
            hooks[1]["command"],
            format!(
                "{} hook session-start --via kiro",
                bin.join("delest").display()
            )
        );
        let main: Value = serde_json::from_str(&render_main(&env)).unwrap();
        assert_eq!(main["hooks"]["agentSpawn"].as_array().unwrap().len(), 2);
    }

    #[test]
    fn installs_into_kiro_dir_when_both_exist() {
        let dir = tempfile::tempdir().unwrap();
        std::fs::create_dir_all(dir.path().join(".kiro").join("agents")).unwrap();
        std::fs::create_dir_all(dir.path().join(".aws").join("amazonq").join("cli-agents"))
            .unwrap();
        let env = Env {
            home: dir.path().to_path_buf(),
            ..Env::default()
        };
        assert_eq!(primary_dir(&env), dir.path().join(".kiro").join("agents"));
    }

    #[test]
    fn marker_is_in_the_rendered_json() {
        let dir = tempfile::tempdir().unwrap();
        let env = env_with_kiro(dir.path());
        let all = subagents::all();
        let content = render(&all[0], &env);
        assert!(content.contains(MARKER));
    }
}
